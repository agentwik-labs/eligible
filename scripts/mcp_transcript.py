"""Turn a recorded Claude Code session (stream-json) into docs/mcp-demo.md and docs/mcp-demo.json.

    claude -p "Can I use my FSA for sunscreen and a massage?" --mcp-config mcp.json \
        --output-format stream-json --verbose ... > stream.jsonl
    uv run python scripts/mcp_transcript.py stream.jsonl logs/mcp_calls.jsonl

The Markdown is the real exchange: the question, each tool call with its arguments, a
trimmed view of each result, and the final answer. The JSON keeps the measurements the
engineering page shows (client cost and time, and each tool call's latency and model cost).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]


def summarize_result(content: Any) -> str:
    text = content if isinstance(content, str) else json.dumps(content)
    try:
        data = json.loads(text if isinstance(content, str) else content[0]["text"])
    except (json.JSONDecodeError, KeyError, IndexError, TypeError):
        return text[:400]
    if isinstance(data, dict) and "verdict" in data:
        cites = ", ".join(c["source_id"] for c in data.get("citations", []))
        return f"verdict **{data['verdict']}**: {data['reason']}\n\n  cites: {cites}"
    return json.dumps(data)[:400]


def main(stream_path: str, calls_path: str) -> None:
    question, steps, final, meta = "", [], "", {}
    for line in Path(stream_path).read_text().splitlines():
        event = json.loads(line)
        kind = event.get("type")
        if kind == "system" and event.get("subtype") == "init":
            meta["tools"] = [t for t in event.get("tools", []) if t.startswith("mcp__eligible")]
            meta["model"] = event.get("model")
        elif kind == "assistant":
            for block in event["message"]["content"]:
                if block["type"] == "tool_use":
                    steps.append(
                        ("call", block["name"].split("__")[-1], json.dumps(block["input"]))
                    )
                elif block["type"] == "text":
                    final = block["text"]
        elif kind == "user":
            for block in event["message"]["content"]:
                if isinstance(block, dict) and block.get("type") == "tool_result":
                    steps.append(("result", "", summarize_result(block.get("content"))))
        elif kind == "result":
            meta.update(
                cost_usd=event.get("total_cost_usd"),
                duration_ms=event.get("duration_ms"),
                turns=event.get("num_turns"),
            )
            question = question or "Can I use my FSA for sunscreen and a massage?"
    calls = [json.loads(line) for line in Path(calls_path).read_text().splitlines() if line.strip()]
    lines = [
        "# MCP demo: Claude using Eligible's tools",
        "",
        "A real session, recorded with Claude Code in headless mode, with only the Eligible MCP",
        f"server connected (tools: {', '.join(t.split('__')[-1] for t in meta.get('tools', []))}).",
        "Generated by `scripts/mcp_transcript.py` from the session's stream; nothing is edited.",
        "",
        f"**Question:** {question}",
        "",
        "## Tool calls",
        "",
    ]
    for kind, name, body in steps:
        lines.append(f"- **{name}** `{body}`" if kind == "call" else f"  - result: {body}")
    lines += ["", "## Claude's answer", "", final, "", "## Measured", ""]
    lines.append(
        f"Client model `{meta.get('model')}`: {meta.get('turns')} turns, "
        f"{meta.get('duration_ms', 0) / 1000:.1f} s, ${meta.get('cost_usd', 0):.4f}."
    )
    lines += ["", "| Tool | Latency | Model cost inside the tool | Detail |", "|---|---|---|---|"]
    lines += [
        f"| {c['tool']} | {c['ms'] / 1000:.1f} s | ${float(c['cost_usd']):.4f} | {c['detail']} |"
        for c in calls
    ]
    lines += [
        "",
        "The first `check_item` call writes the 7,700-token rule preamble to the prompt cache;",
        "the second reads it, which is why it costs a fraction of the first.",
        "",
        "## Add the server to Claude Code or Claude Desktop",
        "",
        "```json",
        '{"mcpServers": {"eligible": {"command": "uv", "args": ["run", "--directory",',
        '  "/path/to/eligible", "python", "-m", "eligible.mcp_server"]}}}',
        "```",
    ]
    (ROOT / "docs" / "mcp-demo.md").write_text("\n".join(lines) + "\n")
    (ROOT / "docs" / "mcp-demo.json").write_text(
        json.dumps(
            {"question": question, "client": meta, "tool_calls": calls, "answer": final}, indent=2
        )
        + "\n"
    )
    print("wrote docs/mcp-demo.md and docs/mcp-demo.json")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
